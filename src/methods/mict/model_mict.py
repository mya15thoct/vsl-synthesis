# DDPM forward process (noise schedule)
# ---------------------------------------------------------------------------

class MicTDDPMScheduler:
    """
    DDPM scheduler for MicT — uses COSINE noise schedule.
    Paper: "αt is generated by the cosine scheduler of the diffusion model"
    (Improved DDPM, Nichol & Dhariwal 2021)

    Supports x0-prediction (model predicts clean motion p0 directly).
    Inference: DDPM reverse I steps, T = T-(1-i/I) per iteration.
    """

    def __init__(self, num_timesteps: int = 1000, s: float = 0.008):
        """
        Args:
            num_timesteps: total diffusion steps T
            s: offset parameter from Improved DDPM paper (default 0.008)
        """
        self.num_timesteps = num_timesteps

        # --- Cosine schedule (Improved DDPM, Eq. 17) ---
        # alpha_bar_t = cos^2( ((t/T + s) / (1 + s)) * pi/2 )
        steps = num_timesteps + 1
        t_vals = torch.linspace(0, num_timesteps, steps)  # 0 .. T
        f = torch.cos(((t_vals / num_timesteps + s) / (1 + s)) * math.pi / 2) ** 2
        alphas_cumprod = f / f[0]                          # normalize so alpha_bar_0 = 1
        alphas_cumprod = alphas_cumprod[1:]               # shape (T,): alpha_bar_1..T
        alphas_cumprod = alphas_cumprod.clamp(min=1e-5)

        # betas from cumprod: beta_t = 1 - alpha_bar_t / alpha_bar_{t-1}
        alpha_bar_prev = torch.cat([torch.ones(1), alphas_cumprod[:-1]])
        betas = (1 - alphas_cumprod / alpha_bar_prev).clamp(0, 0.999)
        alphas = 1.0 - betas

        self.register('betas',            betas)
        self.register('alphas',           alphas)
        self.register('alphas_cumprod',   alphas_cumprod)
        self.register('sqrt_alphas_cumprod',       alphas_cumprod.sqrt())
        self.register('sqrt_one_minus_alphas_cumprod', (1 - alphas_cumprod).sqrt())

    def register(self, name, tensor):
        setattr(self, name, tensor)

    def to(self, device):
        for attr in ['betas', 'alphas', 'alphas_cumprod',
                     'sqrt_alphas_cumprod', 'sqrt_one_minus_alphas_cumprod']:
            setattr(self, attr, getattr(self, attr).to(device))
        return self

    def add_noise(
        self,
        x0: torch.Tensor,     # (B, T, D) clean
        t:  torch.Tensor,     # (B,) int timestep indices
        noise: Optional[torch.Tensor] = None,
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """Sample x_t ~ q(x_t | x_0). Returns (x_t, noise)."""
        if noise is None:
            noise = torch.randn_like(x0)
        sqrt_ac  = self.sqrt_alphas_cumprod[t].view(-1, 1, 1)
        sqrt_omc = self.sqrt_one_minus_alphas_cumprod[t].view(-1, 1, 1)
        x_t = sqrt_ac * x0 + sqrt_omc * noise
        return x_t, noise

    @torch.no_grad()
    def ddpm_step(
        self,
        model: MicTDiffusionModel,
        x_t: torch.Tensor,
        t_int: int,
        masked_seq: torch.Tensor,
        padding_mask: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """
        One reverse DDPM step: compute x_{t-1} from x_t using model's x0 prediction.
        """
        device = x_t.device
        B = x_t.shape[0]
        t_tensor = torch.full((B,), t_int, device=device, dtype=torch.long)

        pred_x0, _ = model(x_t, t_tensor, masked_seq, padding_mask)
        pred_x0 = pred_x0.clamp(-1.5, 1.5)   # safety clamp

        if t_int == 0:
            return pred_x0

        # Compute x_{t-1} from x0 and x_t
        alpha_bar_t = self.alphas_cumprod[t_int]
        alpha_bar_prev = self.alphas_cumprod[t_int - 1]
        beta_t = self.betas[t_int]

        # Posterior mean
        coeff_x0  = (alpha_bar_prev.sqrt() * beta_t)       / (1 - alpha_bar_t)
        coeff_xt  = (self.alphas[t_int].sqrt() * (1 - alpha_bar_prev)) / (1 - alpha_bar_t)
        mean      = coeff_x0 * pred_x0 + coeff_xt * x_t

        # Posterior variance (simplified)
        var   = beta_t * (1 - alpha_bar_prev) / (1 - alpha_bar_t)
        noise = torch.randn_like(x_t) if t_int > 1 else torch.zeros_like(x_t)
        x_prev = mean + var.sqrt() * noise
        return x_prev

    @torch.no_grad()
    def sample(
        self,
        model: MicTDiffusionModel,
        masked_seq: torch.Tensor,            # (B, T, input_dim)
        num_inference_steps: int = 50,
        padding_mask: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """
        Full DDPM reverse sampling.
        Paper inference: T = T - (1 - i/I) per iteration.

        Returns: (B, T, input_dim) generated motion.
        """
        device = masked_seq.device
        B, T, D = masked_seq.shape
        model.eval()

        # Start from pure noise
        x_t = torch.randn(B, T, D, device=device)

        # Timestep schedule: T ... 0  (I steps, fractional decrement)
        I = num_inference_steps
        N = self.num_timesteps
        timestep_seq = [int(N - 1 - (N - 1) * i / I) for i in range(I)]

        for i, t_int in enumerate(timestep_seq):
            x_t = self.ddpm_step(model, x_t, t_int, masked_seq, padding_mask)

        return x_t
